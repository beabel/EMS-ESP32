export type TextKey = keyof typeof en;
export type Texts = (key: TextKey, ...args: (string | number)[]) => string;

const dictionaries: Record<string, typeof en> = { en, de };

export const useTexts = (): Texts => {
  const { locale } = useI18nContext();
  const dict = dictionaries[locale] ?? en;
  return (key, ...args) =>
    dict[key].replace(/\{(\d+)\}/g, (_, i: string) => String(args[Number(i)] ?? ''));
};
